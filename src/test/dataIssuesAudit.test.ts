import { expect, it } from "vitest";
import { trainingRuns } from "../data/trainingRuns";
import prepareTrainingPoints from "../lib/prepareTrainingPoints";
import { describeIssue } from "../lib/describeIssue";
import { paginateIssues } from "../lib/paginateIssues";

it("describes every issue generated by all 20 runs", () => {
    const counts = trainingRuns.map((run) => {
        const { issues } = prepareTrainingPoints(run.generate());

        for (const issue of issues) {
            expect(describeIssue(issue).length).toBeGreaterThan(0);
        }

        const { pageCount } = paginateIssues(issues, 0);
        const reachable = Array.from({ length: pageCount }, (_, page) =>
            paginateIssues(issues, page).entries
        ).flat();
        expect(reachable).toEqual(issues);

        return {
            runId: run.id,
            total: issues.length,
            types: [...new Set(issues.map((issue) => issue.type))],
        };
    });

    expect(counts).toHaveLength(20);
    expect(counts.find((entry) => entry.runId === "Run-19")?.total).toBe(0);
    expect(counts.some((entry) => entry.total > 50)).toBe(true);
    expect(describeIssue({ type: "INVALID_STEP", index: 0, value: NaN })).toContain("NaN");
    console.log(JSON.stringify(counts));
}, 30_000);
